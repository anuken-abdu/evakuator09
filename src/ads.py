def tsv(path, cols, rows):
    lines = ["\t".join(cols)] + ["\t".join(r.get(c, "") for c in cols) for r in rows]
    for l in lines: assert '"' not in l and "\n" not in l, l
    path.write_bytes(("\r\n".join(lines) + "\r\n").encode("utf-16"))

